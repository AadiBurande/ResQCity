"""Choose simulated CCTV camera sites: busy arterial intersections, spread across the city.

Score = w_deg * degree/max_degree + w_btw * betweenness/max_betweenness over candidate junctions
(in-city nodes with >= ``min_degree`` distinct neighbours that touch an arterial road class).
Sites are picked greedily by score, skipping any within ``min_spacing_m`` of a chosen site.
Betweenness is approximated with ``k`` sampled sources (seeded) on base travel times.
"""

from collections import Counter
from pathlib import Path

import networkx as nx
import numpy as np
import yaml
from pydantic import TypeAdapter

from resqcity.common.schemas import Camera
from resqcity.geo.config import CameraSitesConfig
from resqcity.geo.network import RoadNetwork


def approximate_betweenness(network: RoadNetwork, samples: int, seed: int) -> np.ndarray:
    graph = nx.DiGraph()
    graph.add_nodes_from(range(network.n_nodes))
    graph.add_weighted_edges_from(
        zip(
            network.u_idx.tolist(),
            network.v_idx.tolist(),
            network.base_time_s.tolist(),
            strict=True,
        ),
        weight="t",
    )
    k = min(samples, network.n_nodes)
    scores = nx.betweenness_centrality(graph, k=k, weight="t", seed=seed, normalized=True)
    return np.array([scores[i] for i in range(network.n_nodes)])


def select_camera_sites(network: RoadNetwork, cfg: CameraSitesConfig) -> list[Camera]:
    degree = network.distinct_degree()
    arterial = np.zeros(network.n_nodes, dtype=bool)
    is_arterial_edge = network.edges["road_class"].isin(cfg.road_classes).to_numpy()
    arterial[network.u_idx[is_arterial_edge]] = True
    arterial[network.v_idx[is_arterial_edge]] = True
    in_city = network.nodes["in_city"].to_numpy(bool)
    candidates = np.flatnonzero(in_city & arterial & (degree >= cfg.min_degree))
    if len(candidates) == 0:
        return []

    btw = approximate_betweenness(network, cfg.betweenness_samples, cfg.seed)
    deg_c, btw_c = degree[candidates].astype(float), btw[candidates]
    score = cfg.weight_degree * deg_c / deg_c.max()
    if btw_c.max() > 0:
        score = score + cfg.weight_betweenness * btw_c / btw_c.max()
    # Highest score first; ties broken by OSM node id for determinism.
    order = np.lexsort((network.node_ids[candidates], -score))

    chosen: list[int] = []
    for j in order:
        i = candidates[j]
        if all(np.linalg.norm(network.xy[i] - network.xy[c]) >= cfg.min_spacing_m for c in chosen):
            chosen.append(i)
            if len(chosen) == cfg.n:
                break

    width = max(2, len(str(cfg.n)))
    cameras = []
    for rank, i in enumerate(chosen, start=1):
        node = network.nodes.iloc[i]
        cameras.append(
            Camera(
                id=f"C{rank:0{width}d}",
                lat=round(float(node["lat"]), 6),
                lon=round(float(node["lon"]), 6),
                junction_node=int(node["node_id"]),
                ward_id=str(node["ward_id"]),
                fov_note=junction_label(network, i),
            )
        )
    return cameras


def junction_label(network: RoadNetwork, i: int) -> str:
    """Human-readable junction description from the names of the roads meeting there."""
    touching = (network.u_idx == i) | (network.v_idx == i)
    names = Counter(n for n in network.edges.loc[touching, "name"] if isinstance(n, str) and n)
    top = [n for n, _ in names.most_common(2)]
    return "Junction of " + " and ".join(top) if top else "Unnamed junction"


_CAMERAS = TypeAdapter(list[Camera])


def write_cameras_yaml(cameras: list[Camera], path: Path, cfg: CameraSitesConfig) -> None:
    header = (
        "# GENERATED by `python -m resqcity.geo.build`. Do not edit by hand;"
        " change configs/geo.yaml instead.\n"
        f"# n={cfg.n} | "
        f"classes={cfg.road_classes} | min_spacing_m={cfg.min_spacing_m} | seed={cfg.seed}\n"
        "# Sites are real road junctions CHOSEN BY AN ALGORITHM (degree + betweenness); they are\n"
        "# NOT known CCTV locations. Simulated feeds stream public-dataset video (phase 3).\n"
    )
    body = yaml.safe_dump(
        {"cameras": _CAMERAS.dump_python(cameras, mode="json")}, sort_keys=False, allow_unicode=True
    )
    path.write_text(header + body, encoding="utf-8", newline="\n")


def load_cameras(path: Path) -> list[Camera]:
    with path.open(encoding="utf-8") as fh:
        data = yaml.safe_load(fh) or {}
    return _CAMERAS.validate_python(data.get("cameras", []))


def camera_coverage(
    network: RoadNetwork, cameras: list[Camera], radius_m: float
) -> dict[str, np.ndarray]:
    """Node indices within ``radius_m`` (road-graph distance) of each camera's junction."""
    dist = network.shortest_lengths([c.junction_node for c in cameras], limit_m=radius_m)
    return {c.id: np.flatnonzero(np.isfinite(row)) for c, row in zip(cameras, dist, strict=True)}
