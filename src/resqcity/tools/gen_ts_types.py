"""Generate dashboard TypeScript types from the pydantic models in ``common/schemas.py``.

Pure Python (no npm dependency): pydantic JSON schema (serialization mode) -> TypeScript.
Unsupported JSON-schema constructs raise instead of silently producing ``any``.

Usage:
    python -m resqcity.tools.gen_ts_types            # write dashboard/src/types/schemas.ts
    python -m resqcity.tools.gen_ts_types --check    # exit 1 if the committed file is stale
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from pydantic.json_schema import models_json_schema

from resqcity.common.config import PROJECT_ROOT
from resqcity.common.schemas import SCHEMA_MODELS

DEFAULT_OUT = PROJECT_ROOT / "dashboard" / "src" / "types" / "schemas.ts"
HEADER = (
    "// AUTO-GENERATED by resqcity.tools.gen_ts_types from resqcity/common/schemas.py.\n"
    "// DO NOT EDIT. Regenerate with: uv run python -m resqcity.tools.gen_ts_types\n"
    "// Units: durations in seconds, distances in metres, probabilities in [0, 1],\n"
    "// timestamps are ISO-8601 strings with a UTC offset.\n"
)
_REF_PREFIX = "#/$defs/"


def collect_definitions() -> dict[str, dict[str, Any]]:
    """JSON-schema definitions for every exported model and the enums they use."""
    _, top = models_json_schema(
        [(model, "serialization") for model in SCHEMA_MODELS], ref_template=_REF_PREFIX + "{model}"
    )
    return dict(top.get("$defs", {}))


def ts_type(schema: dict[str, Any]) -> str:
    """Translate one JSON-schema fragment into a TypeScript type expression."""
    if "$ref" in schema:
        ref: str = schema["$ref"]
        if not ref.startswith(_REF_PREFIX):
            raise ValueError(f"unsupported $ref: {ref}")
        return ref.removeprefix(_REF_PREFIX)
    if "allOf" in schema and len(schema["allOf"]) == 1:
        return ts_type(schema["allOf"][0])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            members: list[str] = []
            for sub in schema[key]:
                t = ts_type(sub)
                if t not in members:
                    members.append(t)
            return " | ".join(members)
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])

    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>" if "items" in schema else "unknown[]"
    if kind == "object":
        if "properties" in schema:
            raise ValueError("inline object types are not supported; use a named model")
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return f"Record<string, {ts_type(extra)}>"
        return "Record<string, unknown>"
    raise ValueError(f"unsupported JSON schema fragment: {schema!r}")


def _doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    lines = [ln.strip() for ln in text.strip().splitlines() if ln.strip()]
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**", *(f"{indent} * {ln}" for ln in lines), f"{indent} */"]


def render_definition(name: str, schema: dict[str, Any]) -> str:
    out = _doc(schema.get("description"), "")
    if "enum" in schema:
        out.append(f"export type {name} = {ts_type(schema)};")
        values = ", ".join(json.dumps(v) for v in schema["enum"])
        out.append(f"export const {name}Values = [{values}] as const;")
        return "\n".join(out)
    if schema.get("type") != "object" or "properties" not in schema:
        out.append(f"export type {name} = {ts_type(schema)};")
        return "\n".join(out)

    required = set(schema.get("required", []))
    out.append(f"export interface {name} {{")
    for prop, prop_schema in schema["properties"].items():
        out.extend(_doc(prop_schema.get("description"), "  "))
        optional = "" if prop in required else "?"
        out.append(f"  {prop}{optional}: {ts_type(prop_schema)};")
    out.append("}")
    return "\n".join(out)


def render() -> str:
    defs = collect_definitions()
    enums = sorted(n for n, s in defs.items() if "enum" in s)
    others = sorted(n for n in defs if n not in enums)
    blocks = [render_definition(n, defs[n]) for n in [*enums, *others]]
    return HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="fail if the output file is stale")
    args = parser.parse_args(argv)

    content = render()
    out: Path = args.out
    if args.check:
        current = out.read_text(encoding="utf-8") if out.exists() else None
        if current != content:
            print(
                f"{out} is stale; run: uv run python -m resqcity.tools.gen_ts_types",
                file=sys.stderr,
            )
            return 1
        print(f"{out} is up to date")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
